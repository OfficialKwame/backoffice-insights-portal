def compute_failure_analysis(data: pd.DataFrame) -> list:
    failed = data[
        data["normalized_success"] == False
    ].copy()

    if failed.empty:
        return []

    channel_failure_totals = (
        failed.groupby("normalized_channel")
        .size()
        .to_dict()
    )

    grouped = (
        failed.groupby(
            [
                "normalized_channel",
                "clean_failure_reason",
                "raw_provider_response",
            ],
            dropna=False,
        )
        .size()
        .reset_index(name="count")
    )

    results = []

    for _, row in grouped.iterrows():
        channel = row["normalized_channel"]
        count = int(row["count"])

        channel_total = int(
            channel_failure_totals.get(channel, 0)
        )

        share_of_channel_failures = (
            count / channel_total * 100
            if channel_total > 0
            else 0
        )

        raw_response = row["raw_provider_response"]

        if not raw_response:
            raw_response = "No response returned"

        results.append(
            {
                "channel": channel,
                "clean_reason": row[
                    "clean_failure_reason"
                ],
                "raw_provider_response": raw_response,
                "count": count,
                "share_of_channel_failures": round(
                    share_of_channel_failures,
                    2,
                ),
            }
        )

    results.sort(
        key=lambda item: (
            item["channel"],
            -item["count"],
        )
    )

    return results


def compute_unmapped_failure_responses(
    data: pd.DataFrame,
) -> list:
    unmapped = data[
        (data["normalized_success"] == False)
        & (data["clean_failure_reason"] == "UNMAPPED")
    ].copy()

    if unmapped.empty:
        return []

    grouped = (
        unmapped.groupby(
            [
                "normalized_channel",
                "raw_provider_response",
            ],
            dropna=False,
        )
        .size()
        .reset_index(name="count")
        .sort_values(
            by="count",
            ascending=False,
        )
    )

    results = []

    for _, row in grouped.iterrows():
        raw_response = row["raw_provider_response"]

        if not raw_response:
            raw_response = "No response returned"

        results.append(
            {
                "channel": row[
                    "normalized_channel"
                ],
                "raw_provider_response": raw_response,
                "count": int(row["count"]),
            }
        )

    return results


def compute_merchant_activity(data: pd.DataFrame) -> dict:
    eligible = data[
        data["normalized_success"].isin([True, False])
    ].copy()

    business_name_column = BUSINESS_NAME_COLUMN
    business_created_column = BUSINESS_CREATED_COLUMN

    business_created_date_available = bool(
        eligible["_business_created_date_available"].iloc[0]
    ) if not eligible.empty else False

    eligible["normalized_business_id"] = (
        eligible["Businessid"]
        .fillna("")
        .astype(str)
        .str.strip()
    )

    eligible["normalized_business_name"] = (
        eligible[business_name_column]
        .fillna("")
        .astype(str)
        .str.strip()
    )

    eligible["business_created_at"] = pd.to_datetime(
        eligible[business_created_column],
        errors="coerce",
    )

    valid_businesses = eligible[
        eligible["normalized_business_id"] != ""
    ].copy()

    valid_dates = eligible[
        "normalized_payment_date"
    ].dropna()

    if valid_dates.empty:
        period_start = None
        period_end = None
    else:
        period_start = valid_dates.min().normalize()
        period_end = valid_dates.max().normalize()

    active_businesses = int(
        valid_businesses[
            "normalized_business_id"
        ].nunique()
    )

    successful_businesses = valid_businesses[
        valid_businesses["normalized_success"] == True
    ]

    businesses_that_collected = int(
        successful_businesses[
            "normalized_business_id"
        ].nunique()
    )

    business_records = (
        valid_businesses[
            [
                "normalized_business_id",
                "normalized_business_name",
                "business_created_at",
            ]
        ]
        .sort_values(
            "business_created_at",
            na_position="last",
        )
        .drop_duplicates(
            subset=["normalized_business_id"],
            keep="first",
        )
    )

    if (
        not business_created_date_available
        or period_start is None
        or period_end is None
    ):
        new_businesses = None
    else:
        new_businesses = int(
            business_records[
                business_records["business_created_at"].between(
                    period_start,
                    period_end + pd.Timedelta(days=1),
                    inclusive="left",
                )
            ]["normalized_business_id"].nunique()
        )

    total_collected_value = float(
        valid_businesses.loc[
            valid_businesses["normalized_success"] == True,
            "Amountpaid",
        ].sum()
    )

    merchants = []

    for business_id, group in valid_businesses.groupby(
        "normalized_business_id"
    ):
        attempts = len(group)

        successful = int(
            (group["normalized_success"] == True).sum()
        )

        failed = int(
            (group["normalized_success"] == False).sum()
        )

        success_rate = (
            successful / attempts * 100
            if attempts > 0
            else 0
        )

        collected_value = float(
            group.loc[
                group["normalized_success"] == True,
                "Amountpaid",
            ].sum()
        )

        failed_value = float(
            group.loc[
                group["normalized_success"] == False,
                "Amountpaid",
            ].sum()
        )

        collection_share = (
            collected_value / total_collected_value * 100
            if total_collected_value > 0
            else 0
        )

        names = group[
            "normalized_business_name"
        ].loc[
            group["normalized_business_name"] != ""
        ]

        business_name = (
            names.iloc[0]
            if not names.empty
            else "Unnamed Business"
        )

        failed_transactions = group[
            group["normalized_success"] == False
        ].copy()

        failure_reasons = []

        if not failed_transactions.empty:
            failure_groups = (
                failed_transactions.groupby(
                    [
                        "normalized_channel",
                        "clean_failure_reason",
                        "raw_provider_response",
                    ],
                    dropna=False,
                )
                .size()
                .reset_index(name="count")
            )

            for _, failure_row in failure_groups.iterrows():
                count = int(failure_row["count"])

                share_of_merchant_failures = (
                    count / failed * 100
                    if failed > 0
                    else 0
                )

                channel = failure_row[
                    "normalized_channel"
                ]

                clean_reason = failure_row[
                    "clean_failure_reason"
                ]

                raw_response = failure_row[
                    "raw_provider_response"
                ]

                failure_reasons.append(
                    {
                        "channel": (
                            str(channel)
                            if pd.notna(channel)
                            else "Unknown"
                        ),
                        "clean_reason": (
                            str(clean_reason)
                            if pd.notna(clean_reason)
                            else "UNMAPPED"
                        ),
                        "raw_provider_response": (
                            str(raw_response)
                            if pd.notna(raw_response)
                            else ""
                        ),
                        "count": count,
                        "share_of_merchant_failures": round(
                            share_of_merchant_failures,
                            2,
                        ),
                    }
                )

            failure_reasons.sort(
                key=lambda item: item["count"],
                reverse=True,
            )

        merchants.append(
            {
                "business_id": business_id,
                "business_name": business_name,
                "attempts": attempts,
                "successful": successful,
                "failed": failed,
                "success_rate": round(
                    success_rate,
                    2,
                ),
                "collected_value": round(
                    collected_value,
                    2,
                ),
                "failed_value": round(
                    failed_value,
                    2,
                ),
                "collection_share": round(
                    collection_share,
                    2,
                ),
                "failure_reasons": failure_reasons,
            }
        )

    merchants.sort(
        key=lambda item: item["collected_value"],
        reverse=True,
    )

    invalid_created_dates = (
        int(
            business_records[
                "business_created_at"
            ].isna().sum()
        )
        if business_created_date_available
        else 0
    )

    return {
        "reporting_period": {
            "start": (
                period_start.date().isoformat()
                if period_start is not None
                else None
            ),
            "end": (
                period_end.date().isoformat()
                if period_end is not None
                else None
            ),
        },
        "active_businesses": active_businesses,
        "businesses_that_collected": businesses_that_collected,
        "new_businesses": new_businesses,
        "top_merchants": merchants,
        "data_quality": {
            "transactions_missing_business_id": int(
                (
                    eligible["normalized_business_id"] == ""
                ).sum()
            ),
            "transactions_missing_business_name": int(
                (
                    eligible["normalized_business_name"] == ""
                ).sum()
            ),
            "business_created_date_available": (
                business_created_date_available
            ),
            "businesses_with_invalid_created_date": (
                invalid_created_dates
            ),
        },
    }


def compute_data_quality(data: pd.DataFrame) -> dict:
    failed = data[
        data["normalized_success"] == False
    ]

    return {
        "unrecognized_success_statuses": int(
            data["normalized_success"].isna().sum()
        ),
        "unknown_channels": int(
            (data["normalized_channel"] == "Unknown").sum()
        ),
        "invalid_payment_dates": int(
            data["normalized_payment_date"].isna().sum()
        ),
        "failed_transactions_without_reason": int(
            (
                (failed["raw_provider_response"] == "")
                | failed["Providerdescription"].isna()
            ).sum()
        ),
        "unmapped_failed_transactions": int(
            (
                failed["clean_failure_reason"]
                == "UNMAPPED"
            ).sum()
        ),
    }


def run_compute(file_path: str) -> dict:
    raw_data = load_file(file_path)
    data = prepare_data(raw_data)

    return {
        "overall": compute_core_metrics(data),
        "daily_trend": compute_daily_trend(data),
        "channel_daily_trend": compute_channel_daily_trend(data),
        "channels": compute_channel_performance(data),
        "failure_analysis": compute_failure_analysis(data),
        "unmapped_failure_responses": (
            compute_unmapped_failure_responses(data)
        ),
        "merchant_activity": compute_merchant_activity(data),
        "data_quality": compute_data_quality(data),
    }

if __name__ == "__main__":
    if len(sys.argv) != 2:
        print(
            "Usage: python3 compute/collections/compute.py "
            "<path-to-data-file>"
        )
        sys.exit(1)

    result = run_compute(sys.argv[1])

    print(json.dumps(result, indent=2))